JL.chemistry.get_element = function( p ){
	var match;
	if     ( p.symbol !== undefined ) match = this.elements.find( x => x.symbol == p.symbol );
	else if( p.name   !== undefined ){
		var name = p.name.toLowerCase();
		match = this.elements.find( x => x.name.toLowerCase() == name );
	}

	if( match ) return Object.assign( {}, match );
};

JL.chemistry.get_orbital_from_num_electrons = function( num_electrons ){
	return this.get_electron_configuration( num_electrons ).pop();
};

JL.chemistry.get_electron_configuration = function( num_electrons ){
	if( num_electrons <= 0 || !num_electrons ) return { level : 0, orbital : '', electrons : 0, };

	var subshell_types = [ 's', 'p', 'd', 'f', 'g', 'h', 'i', 'k', 'l', 'm', 'n' ];
	var subshells      = [];
	for( var sum = 1; sum <= 20; sum++ ){
		for( var n = sum; n >= 1; n-- ){
			var l = sum - n;
			if( l < n && l < subshell_types.length ){
				subshells.push({
					orbital  : subshell_types[l],
					capacity : 4 * l + 2,
					sum      : sum,
					level    : n,
				});
			}
		}
	}

	subshells.sort(function(a,b){
		if( a.sum !== b.sum ) return a.sum - b.sum;
		return a.level - b.level;
	});

	var output = [];
	var remaining_electrons = num_electrons;

	for( var subshell of subshells ){
		if( remaining_electrons <= 0 ) break;

		var electrons = Math.min( remaining_electrons, subshell.capacity );
		output.push({ level : subshell.level, orbital : subshell.orbital, electrons, });
		remaining_electrons -= electrons;
	}

	return output;
};

JL.chemistry.get_max_valency = function( p ){
	var group;
	if( p.group !== undefined ) group = p.group;
	else                        group = this.get_element( p ).group;

	if( group === 18 ) return 0;  // noble gases

	var valence_electrons = ( group > 12 ? group - 10 : group );

	if( valence_electrons > 4 ) return 8 - valence_electrons;
	return valence_electrons;
}

JL.chemistry.load_rdkit = function( p ){
	var p = p || {};

	var self = this;

	if( !this.RDKit ){
		$.ajax({
			url      : './assets/lib/jl/chemistry/RDKit_minimal.js',
			dataType : "script",
			async    : false,
			success  : function() {
				window.initRDKitModule().then(function( RDKit ){
					self.RDKit = RDKit;
					if( p.callback ) p.callback();
				});
			}
		});
	}
	else{
		if( p.callback ) p.callback();
	}
};

JL.chemistry.parse_smiles = function( p ){
	var self = this;

	this.load_rdkit({ callback : function(){
		var vector = {
			sub       : function(v1, v2){ return { x: v1.x - v2.x, y: v1.y - v2.y, z: v1.z - v2.z }; },
			add       : function(v1, v2){ return { x: v1.x + v2.x, y: v1.y + v2.y, z: v1.z + v2.z }; },
			scale     : function(v , s ){ return { x: v.x * s, y: v.y * s, z: v.z * s }            ; },
			normalize : function( v ){
				var len = Math.hypot( v.x, v.y, v.z );
				return ( len === 0 ? { x : 0, y : 0, z : 0 } : { x: v.x / len, y: v.y / len, z: v.z / len } );
			},
		};

		var original_mol = self.RDKit.get_mol( p.smiles );
		var mol_with_H   = self.RDKit.get_mol( original_mol.add_hs() );

		mol_with_H.set_new_coords(); // Generate flat 2D layout (Z will be 0)

		var lines = mol_with_H.get_molblock().split('\n');

		original_mol.delete();
		mol_with_H  .delete();

		var counts_line = lines[3];
		var num_atoms   = parseInt( counts_line.substring(0, 3).trim(), 10 );
		var num_bonds   = parseInt( counts_line.substring(3, 6).trim(), 10 );

		var atoms = [];
		var line_idx = 4;

		for( var i = 0; i < num_atoms; i++ ){
			var line = lines[line_idx++];
			atoms.push({
				id     : i + 1,
				x      : parseFloat(line.substring(0, 10).trim()),
				y      : parseFloat(line.substring(10, 20).trim()),
				z      : 0.0, // Default to 0, we will calculate this for H
				symbol : line.substring(31, 34).trim()
			});
		}

		var bonds = [];
		for( var i = 0; i < num_bonds; i++ ){
			var line = lines[line_idx++];
			bonds.push({
				from  : parseInt(line.substring(0, 3).trim(), 10),
				to    : parseInt(line.substring(3, 6).trim(), 10),
				order : parseInt(line.substring(6, 9).trim(), 10)
			});
		}

		var mol_data = { total_atoms: num_atoms, atoms: atoms, bonds: bonds };

		var BOND_LENGTH = 1.09; // Standard C-H bond length in Angstroms

		var graph = {}; // Build adjacency graph to know which atoms are connected
		mol_data.atoms.forEach(a => graph[a.id] = { atom: a, heavy: [], hydro: [] });

		mol_data.bonds.forEach(function(b){
			var a1 = mol_data.atoms[ b.from - 1 ];
			var a2 = mol_data.atoms[ b.to   - 1 ];

			if     ( a2.symbol === 'H' ) graph[a1.id].hydro.push(a2);
			else if( a1.symbol !== 'H' ) graph[a1.id].heavy.push(a2);

			if     ( a1.symbol === 'H' ) graph[a2.id].hydro.push(a1);
			else if( a2.symbol !== 'H' ) graph[a2.id].heavy.push(a1);
		});

		mol_data.atoms.forEach(function( central ){
		if( central.symbol === 'H' ) return; // Skip hydrogens themselves

		var node = graph[central.id];
		if( node.hydro.length === 0 ) return; // No hydrogens to place

		var heavy_count = node.heavy.length;
		var hydro_count = node.hydro.length;

		if( heavy_count === 1 ){
			var neighbor = node.heavy[0];
			var dir      = vector.normalize(vector.sub(central, neighbor));
			var ortho    = { x: -dir.y, y: dir.x, z: 0 }; // Perpendicular in XY plane

			if( hydro_count === 1 ){
				var pos = vector.add(central, vector.scale(dir, BOND_LENGTH));
				Object.assign(node.hydro[0], pos);
			} 
			else if( hydro_count === 2 ){
				var v1 = vector.add(vector.scale(dir, 0.5), vector.scale(ortho, 0.866));
				var v2 = vector.add(vector.scale(dir, 0.5), vector.scale(ortho, -0.866));
				Object.assign(node.hydro[0], vector.add(central, vector.scale(v1, BOND_LENGTH)));
				Object.assign(node.hydro[1], vector.add(central, vector.scale(v2, BOND_LENGTH)));
			} 
			else if( hydro_count === 3 ){
				var h1_dir = dir;
				var h2_dir = vector.normalize({ x: -dir.x * 0.33, y: -dir.y * 0.33, z: 0.94 });
				var h3_dir = vector.normalize({ x: -dir.x * 0.33, y: -dir.y * 0.33, z: -0.94 });

				Object.assign(node.hydro[0], vector.add(central, vector.scale(h1_dir, BOND_LENGTH)));
				Object.assign(node.hydro[1], vector.add(central, vector.scale(h2_dir, BOND_LENGTH)));
				Object.assign(node.hydro[2], vector.add(central, vector.scale(h3_dir, BOND_LENGTH)));
			}
		}
		else if( heavy_count === 2 ){
			var v1 = vector.normalize(vector.sub(node.heavy[0], central));
			var v2 = vector.normalize(vector.sub(node.heavy[1], central));

			var bisect = vector.normalize(vector.add(v1, v2));

			var outward = vector.scale(bisect, -1);

			if( hydro_count === 1 ){
				var pos = vector.add(central, vector.scale(outward, BOND_LENGTH));
				Object.assign(node.hydro[0], pos);
			} 
			else if( hydro_count === 2 ){
				var h1_dir = vector.normalize({ x: outward.x * 0.6, y: outward.y * 0.6, z: 0.8 });
				var h2_dir = vector.normalize({ x: outward.x * 0.6, y: outward.y * 0.6, z: -0.8 });

				Object.assign(node.hydro[0], vector.add(central, vector.scale(h1_dir, BOND_LENGTH)));
				Object.assign(node.hydro[1], vector.add(central, vector.scale(h2_dir, BOND_LENGTH)));
			}
		}
		else if( heavy_count === 3 ){
			if( hydro_count === 1 ){
				node.hydro[0].x = central.x;
				node.hydro[0].y = central.y;
				node.hydro[0].z = central.z + BOND_LENGTH;
			}
		}
		});

		for( var atom of mol_data.atoms ){
			if( self.get_element ) atom.config = self.get_element({ symbol: atom.symbol });
		}

		if( p.callback ) p.callback( mol_data );
	} });
};

